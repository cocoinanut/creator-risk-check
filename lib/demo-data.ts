export type Creator = (typeof creators)[number];
export function evidenceFor(c: Creator): Evidence[] {
  return c.raw.map((r) => ({
    id: c.id + "-" + r[0],
    title: r[1],
    publisher: r[2],
    date: r[3],
    type: r[4],
    excerpt: r[5],
    supports: r[6],
    limits: r[7],
  }));
}
export function scoring(c: Creator) {
  const base =
    Math.round(
      c.scores.reduce((a, n, i) => a + (n * dimensions[i].weight) / 100, 0) *
        100,
    ) / 100;
  const score = Math.max(Math.round(base), c.floor);
  return {
    base,
    score,
    adjustment: c.floor ? Math.round((score - base) * 100) / 100 : 0,
    level: score < 30 ? "低" : score < 60 ? "中" : "高",
  };
}
export const allEvidence = creators.flatMap(evidenceFor);
export function resolveSearch(input: string) {
  const aliases: Record<string, string> = {
    "woodland notes": "林间手记",
    "weekend lab": "周末开箱局",
    "aran outdoors": "极限阿燃",
  };
  const raw = input.trim().toLowerCase();
  const q = aliases[raw] ?? raw;
  if (!q)
    return { matches: [], platform: "", error: "请输入名字、@ID 或主页链接。" };
  let handle = q.replace(/^@/, "");
  let platform = "";
  if (
    /^https?:\/\//.test(q) ||
    /^(www\.)?(instagram\.com|tiktok\.com|youtube\.com)\//.test(q)
  ) {
    try {
      const url = new URL(q.startsWith("http") ? q : "https://" + q);
      const host = url.hostname.replace(/^www\./, "");
      platform =
        host === "instagram.com"
          ? "Instagram"
          : host === "tiktok.com"
            ? "TikTok"
            : host === "youtube.com"
              ? "YouTube"
              : "";
      if (!platform)
        return {
          matches: [],
          platform: "",
          error: "此链接不是支持的平台主页，无法确认身份，已停止评分。",
        };
      const parts = url.pathname.split("/").filter(Boolean);
      if (
        parts.length !== 1 ||
        (platform !== "Instagram" && !parts[0].startsWith("@"))
      )
        return {
          matches: [],
          platform,
          error:
            "请输入账号主页链接，而非帖子、视频或短链接。身份未确认，无法评分。",
        };
      handle = parts[0].replace(/^@/, "");
    } catch {
      return {
        matches: [],
        platform,
        error: "链接格式无法识别，身份未确认，无法评分。",
      };
    }
  }
  const isHandle = q.startsWith("@") || !!platform;
  const matches = creators.filter((c) =>
    isHandle ? c.handle === handle : c.name.includes(q) || c.handle === handle,
  );
  return {
    matches,
    platform,
    error: matches.length
      ? ""
      : "未找到对应演示案例。请通过「真实资料检索」查询真实人物；此处不会用虚构资料评分。",
  };
}
